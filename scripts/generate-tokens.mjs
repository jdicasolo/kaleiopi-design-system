// Generates the Kaleiopi 50–950 brand scales described in kaleiopi/docs/brand-colors.md:
// fixed hue + saturation, HSL lightness interpolated toward white/black, with each
// literal brand hex anchored exactly on its step. Writes src/tokens/theme.css and
// src/tokens/palette.json (the latter feeds the Colors docs page).
import { writeFileSync } from 'node:fs';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
// Lightness Tailwind-style scales roughly land on; the anchor overrides its own step
// and the neighbours are interpolated between the anchor and these end points.
const LIGHTEST = 97;
const DARKEST = 12;

const BRAND = {
  navy: { hex: '#02154C', step: 950, role: 'Core identity — brand wordmark, footer' },
  purple: { hex: '#6245A1', step: 600, role: 'Core identity — primary buttons, links, active states, focus rings' },
  teal: { hex: '#08A8B1', step: 700, role: 'Core identity — decorative/structural accents only' },
  gold: { hex: '#E6AE49', step: 500, role: 'Kaleidoscope accent — streaks, celebratory moments, donation CTA' },
  pink: { hex: '#CA618E', step: 500, role: 'Kaleidoscope accent — progress bars, step indicators' },
  blue: { hex: '#025298', step: 800, role: 'Kaleidoscope accent — reserved for future use' },
};

const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
function rgbToHsl([r, g, b]) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l * 100];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s * 100, l * 100];
}
function hslToHex(h, s, l) {
  s /= 100; l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return '#' + [f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
}
const lum = (hex) => hexToRgb(hex).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)).reduce((acc, c, i) => acc + c * [0.2126, 0.7152, 0.0722][i], 0);
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const palette = {};
let css = '/* Generated by scripts/generate-tokens.mjs — do not edit by hand. */\n@theme {\n';
for (const [name, { hex, step, role }] of Object.entries(BRAND)) {
  const [h, s, l] = rgbToHsl(hexToRgb(hex));
  const ai = STEPS.indexOf(step);
  const scale = STEPS.map((st, i) => {
    if (i === ai) return [st, hex];
    const L = i < ai ? LIGHTEST + (l - LIGHTEST) * (i / ai) : l + (DARKEST - l) * ((i - ai) / (STEPS.length - 1 - ai));
    return [st, hslToHex(h, s, L)];
  });
  css += `  --color-kaleiopi-${name}: ${hex};\n`;
  for (const [st, v] of scale) css += `  --color-kaleiopi-${name}-${st}: ${v};\n`;
  palette[name] = { hex, anchor: step, role, contrastOnWhite: +contrast(hex, '#FFFFFF').toFixed(2),
    scale: scale.map(([st, v]) => ({ step: st, hex: v, onWhite: +contrast(v, '#FFFFFF').toFixed(2) })) };
}
css += '}\n';
writeFileSync(new URL('../src/tokens/theme.css', import.meta.url), css);
writeFileSync(new URL('../src/tokens/palette.json', import.meta.url), JSON.stringify(palette, null, 2) + '\n');
